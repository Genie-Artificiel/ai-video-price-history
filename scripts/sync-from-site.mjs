#!/usr/bin/env node
// Keeps data/ byte-identical to the CSV files served by genie-artificiel.com, and the docs in line with the data.
//
// The site builds both CSV files from its own sources into site/dist/media/donnees/. This script copies them
// here when they changed, regenerates the stats block of README.md, then checks every document it is given
// (README.md and CITATION.cff, plus any extra path) against the data: observation and tool counts, date range,
// tool names, and no affiliate vocabulary or /go/ links. Plain Node (22+), no dependencies.
//
//   node scripts/sync-from-site.mjs                 copy changed files, update the stats block, check the docs
//   node scripts/sync-from-site.mjs --check         change nothing; exit 1 on any difference
//   node scripts/sync-from-site.mjs --online        also compare the site build with the files in production
//   node scripts/sync-from-site.mjs [...] card.md   also check card.md (a dataset card, a pull request text…)
//
// --dist <dir> points at the site build (default: ../../site/dist from the repository root, or $SITE_DIST).
import { createHash } from 'node:crypto';
import { copyFileSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SITE = 'https://www.genie-artificiel.com';
const SERVED_DIR = '/media/donnees/';
const DATA = 'historique-prix-outils-ia.csv';
const DICTIONARY = 'historique-prix-outils-ia-dictionary.csv';
const STATS_BEGIN = '<!-- stats:begin (generated by scripts/sync-from-site.mjs, do not edit) -->';
const STATS_END = '<!-- stats:end -->';
// The dataset is published without any affiliate wording or tracked link (rule of the publisher).
const FORBIDDEN = [/\/go\//, /affiliat/i, /commission/i, /sponsor/i, /utm_/i];

const args = process.argv.slice(2);
const check = args.includes('--check');
const online = args.includes('--online');
const distArg = args.indexOf('--dist');
const dist = resolve(distArg >= 0 ? args[distArg + 1] : process.env.SITE_DIST ?? join(ROOT, '..', '..', 'site', 'dist'));
const extraDocs = args.filter((a, i) => !a.startsWith('--') && !(distArg >= 0 && i === distArg + 1)).map(p => resolve(p));

const problems = [];
const notes = [];
let stats = null;
const rel = p => { const r = relative(process.cwd(), p) || '.'; return r.startsWith('../../..') ? p : r; };
const sha = buf => createHash('sha256').update(buf).digest('hex');

/** RFC 4180 parser: quoted fields, doubled quotes, CRLF or LF. Returns rows of strings. */
function parseCsv(text) {
  const rows = [];
  let row = [], field = '', quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++;
      row.push(field); rows.push(row); row = []; field = '';
    } else field += c;
  }
  if (field !== '' || row.length) { row.push(field); rows.push(row); }
  return rows;
}

const countRows = buf => parseCsv(buf.toString('utf8').replace(/^\uFEFF/, '')).length - 1;

// 1. Site build → data/
for (const name of [DATA, DICTIONARY]) {
  const from = join(dist, SERVED_DIR, name);
  const to = join(ROOT, 'data', name);
  if (!existsSync(from)) { problems.push(`${rel(from)} not found: build the site first (npm run build in site/) or pass --dist`); continue; }
  const built = readFileSync(from);
  const kept = existsSync(to) ? readFileSync(to) : null;
  if (kept && sha(kept) === sha(built)) { notes.push(`${name}: identical to the site build (${built.length} bytes, sha256 ${sha(built).slice(0, 12)}…)`); continue; }
  const change = kept ? `${kept.length} → ${built.length} bytes, ${countRows(kept)} → ${countRows(built)} rows` : 'missing here';
  if (check) problems.push(`${name} differs from the site build (${change})`);
  else { copyFileSync(from, to); notes.push(`${name}: UPDATED from the site build (${change}); bump version and date-released in CITATION.cff`); }
}

// 2. Site build ↔ production (optional: the build may hold changes not deployed yet, or the reverse)
if (online) {
  for (const name of [DATA, DICTIONARY]) {
    const from = join(dist, SERVED_DIR, name);
    if (!existsSync(from)) continue;
    const url = `${SITE}${SERVED_DIR}${name}`;
    try {
      const res = await fetch(`${url}?v=${Date.now()}`);
      if (!res.ok) { problems.push(`${url}: HTTP ${res.status}`); continue; }
      const served = Buffer.from(await res.arrayBuffer());
      if (sha(served) === sha(readFileSync(from))) notes.push(`${name}: identical to the file served in production`);
      else problems.push(`${name}: the site build differs from production (${url}); deploy or rebuild before publishing`);
    } catch (e) { problems.push(`${url}: ${e.message}`); }
  }
}

// 3. Structure and figures of the data
const dataPath = join(ROOT, 'data', DATA);
if (!existsSync(dataPath)) { report(); process.exit(1); }
const raw = readFileSync(dataPath, 'utf8');
if (!raw.startsWith('\uFEFF')) problems.push(`${DATA}: UTF-8 byte order mark missing`);
const [header, ...rows] = parseCsv(raw.replace(/^\uFEFF/, ''));
const dictRows = parseCsv(readFileSync(join(ROOT, 'data', DICTIONARY), 'utf8').replace(/^\uFEFF/, '')).slice(1);
const documented = dictRows.map(r => r[0]);
if (header.join() !== documented.join()) problems.push(`${DATA}: header (${header.join(', ')}) does not match the dictionary (${documented.join(', ')})`);
rows.forEach((r, i) => { if (r.length !== header.length) problems.push(`${DATA}: row ${i + 2} has ${r.length} fields, expected ${header.length}`); });
const obs = rows.map(r => Object.fromEntries(header.map((h, i) => [h, r[i] ?? ''])));

const by = (key, list = obs) => list.reduce((m, o) => m.set(o[key], (m.get(o[key]) ?? 0) + 1), new Map());
const tools = [...new Map(obs.map(o => [o.tool, o.category])).entries()];
const dates = obs.map(o => o.date).sort();
stats = {
  rows: obs.length, tools: tools.length, from: dates[0], to: dates.at(-1),
  wayback: obs.filter(o => o.source.startsWith('https://web.archive.org/')).length,
  noPrice: obs.filter(o => !o.monthly_price_billed_monthly && !o.monthly_price_billed_annually).length,
};
const list = m => [...m].map(([k, n]) => `${n} ${k}`).join(', ');

// 4. README stats block, regenerated from the data
const block = [
  STATS_BEGIN,
  `- **${stats.rows} observations** of **${stats.tools} tools**, dated ${stats.from} to ${stats.to}.`,
  `- Prices: ${list(by('currency', obs.filter(o => o.monthly_price_billed_monthly || o.monthly_price_billed_annually)))}; ${stats.noPrice} rows only record credit rates, without a plan price.`,
  `- Confidence: ${list(by('confidence'))}.`,
  `- Sources: ${stats.wayback} rows cite a Wayback Machine capture, ${stats.rows - stats.wayback} the live official page on the date shown.`,
  '',
  '| Tool | Category | Observations | First | Last |',
  '|---|---|---|---|---|',
  ...tools.map(([tool, category]) => {
    const own = obs.filter(o => o.tool === tool).map(o => o.date).sort();
    return `| ${tool} | ${category} | ${own.length} | ${own[0]} | ${own.at(-1)} |`;
  }),
  STATS_END,
].join('\n');

const readmePath = join(ROOT, 'README.md');
if (existsSync(readmePath)) {
  const readme = readFileSync(readmePath, 'utf8');
  const start = readme.indexOf(STATS_BEGIN), end = readme.indexOf(STATS_END);
  if (start < 0 || end < start) problems.push('README.md: stats markers not found');
  else if (readme.slice(start, end + STATS_END.length) !== block) {
    if (check) problems.push('README.md: stats block out of date (run without --check)');
    else { writeFileSync(readmePath, readme.slice(0, start) + block + readme.slice(end + STATS_END.length)); notes.push('README.md: stats block UPDATED'); }
  }
} else problems.push('README.md not found');

// 5. Figures quoted in the documents; every version number (YYYY.MM.DD) must be the one in CITATION.cff
const citationPath = join(ROOT, 'CITATION.cff');
const version = existsSync(citationPath) ? readFileSync(citationPath, 'utf8').match(/^version: "?([\d.]+)"?$/m)?.[1] : null;
if (!version) problems.push('CITATION.cff: version not found');
for (const doc of [readmePath, citationPath, ...extraDocs]) {
  if (!existsSync(doc)) { problems.push(`${rel(doc)} not found`); continue; }
  const text = readFileSync(doc, 'utf8');
  const name = rel(doc);
  for (const [, n] of text.matchAll(/\b(\d[\d,]*) (?:dated )?observations\b/g)) if (Number(n.replace(/,/g, '')) !== stats.rows) problems.push(`${name}: "${n} observations", the data has ${stats.rows}`);
  for (const [, n] of text.matchAll(/\b(\d+) (?:AI )?tools\b/g)) if (Number(n) !== stats.tools) problems.push(`${name}: "${n} tools", the data has ${stats.tools}`);
  for (const [, n] of text.matchAll(/\b(\d+) Wayback Machine captures\b/g)) if (Number(n) !== stats.wayback) problems.push(`${name}: "${n} Wayback Machine captures", the data has ${stats.wayback}`);
  for (const [, n] of text.matchAll(/\b(\d+) live (?:official )?pages\b/g)) if (Number(n) !== stats.rows - stats.wayback) problems.push(`${name}: "${n} live pages", the data has ${stats.rows - stats.wayback}`);
  if (!/\b\d[\d,]* (?:dated )?observations\b/.test(text)) problems.push(`${name}: never states the number of observations`);
  for (const d of [stats.from, stats.to]) if (!text.includes(d)) problems.push(`${name}: date ${d} (start or end of the data) not mentioned`);
  for (const [tool] of tools) if (!text.includes(tool)) problems.push(`${name}: tool "${tool}" not mentioned`);
  for (const [v] of text.matchAll(/\b20\d\d\.\d\d\.\d\d\b/g)) if (version && v !== version) problems.push(`${name}: version ${v}, CITATION.cff says ${version}`);
  for (const re of FORBIDDEN) if (re.test(text)) problems.push(`${name}: forbidden wording ${re}`);
}
for (const name of [DATA, DICTIONARY]) {
  const text = readFileSync(join(ROOT, 'data', name), 'utf8');
  for (const re of FORBIDDEN) if (re.test(text)) problems.push(`${name}: forbidden wording ${re}`);
}

report();
process.exit(problems.length ? 1 : 0);

function report() {
  for (const n of notes) console.log(`  ${n}`);
  if (problems.length) {
    console.error(`\n${problems.length} difference(s):`);
    for (const p of problems) console.error(`  - ${p}`);
  } else console.log(`\nOK: no difference (${stats?.rows ?? '?'} observations, ${stats?.tools ?? '?'} tools, ${stats?.from ?? '?'} to ${stats?.to ?? '?'}).`);
}
